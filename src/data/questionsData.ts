// Helper to filter/generate randomized tests according to country and mode
import { QuestionCategory } from '../types';
import { BILINGUAL_COUNTRIES_DATA, BilingualQuestion, GLOBAL_BILINGUAL_QUESTIONS } from './bilingualCountriesData';

export function getQuestionsForTest(
  countryId: string,
  mode: string,
  locale: 'ar' | 'en',
  requestedCount?: number
): Question[] {
  const countryData = BILINGUAL_COUNTRIES_DATA[countryId];
  
  // Use specific country questions if available, otherwise just global
  const specificQuestions = countryData ? countryData.questions : [];
  const combinedPool = [...specificQuestions, ...GLOBAL_BILINGUAL_QUESTIONS];

  const pool = combinedPool.map((q: BilingualQuestion): Question => {
    // Map category string to QuestionCategory
    const categoryName = q.category[locale];
    let category: QuestionCategory = 'general';
    if (categoryName.includes('إشارة') || categoryName.includes('Sign')) category = 'signs';
    else if (categoryName.includes('أولوية') || categoryName.includes('Priority')) category = 'priority';
    else if (categoryName.includes('مخالف') || categoryName.includes('Violation')) category = 'violations';
    else if (categoryName.includes('أمان') || categoryName.includes('Safety')) category = 'safety';

    return {
      id: q.id,
      countryId: countryId as any,
      category,
      categoryName,
      questionText: q[locale].questionText,
      options: q[locale].options.map((text, index) => ({
        id: String.fromCharCode(65 + index), // 'A', 'B', 'C', 'D'
        text,
      })),
      correctOptionId: String.fromCharCode(65 + q.correctAnswerIndex),
      explanation: q[locale].explanation,
      difficulty: 'medium', // Default
    };
  });

  // Shuffle pool using Fisher-Yates
  const shuffled = [...pool];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }

  let count = requestedCount || (mode === 'quick_10' ? 10 : 20);
  if (count > shuffled.length) {
    count = shuffled.length;
  }

  return shuffled.slice(0, count);
}

